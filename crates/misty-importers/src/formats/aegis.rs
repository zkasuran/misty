//! Aegis Authenticator vaults, plain and encrypted.
//!
//! # The format
//!
//! ```json
//! { "version": 1,
//!   "header": { "slots": null, "params": null },
//!   "db": { "version": 3, "entries": [ … ], "groups": [ … ] } }
//! ```
//!
//! When the vault is encrypted, `db` is a base64 string and `header` carries the
//! key material:
//!
//! ```json
//! { "version": 1,
//!   "header": {
//!     "slots": [ { "type": 1, "uuid": "…", "key": "<hex>",
//!                  "key_params": { "nonce": "<hex>", "tag": "<hex>" },
//!                  "n": 32768, "r": 8, "p": 1, "salt": "<hex>" } ],
//!     "params": { "nonce": "<hex>", "tag": "<hex>" } },
//!   "db": "<base64>" }
//! ```
//!
//! Each slot holds the 256-bit master key, encrypted under a key scrypt derives
//! from one password. `db` is AES-256-GCM under the master key, with the nonce and
//! the tag in `header.params` — the tag is **not** appended to the ciphertext, which
//! is the detail an implementation from the outside gets wrong. The plaintext is
//! the `db` **object** on its own, not a whole vault file.
//!
//! Source: Aegis's `docs/vault.md` and `VaultFile.java` / `PasswordSlot.java` /
//! `CryptoUtils.java` in `beemdevelopment/Aegis`. Reproduced here rather than
//! guessed, and the encrypted fixture in `tests/fixtures/aegis/` is generated by
//! `tests/fixture_provenance.rs` so the shape is checked rather than asserted.
//!
//! # Deliberate strictness
//!
//! An unknown top-level `version` is refused. Aegis has written `1` since the
//! format existed; a `2` would mean a change this code has not seen, and reading a
//! credential file on the assumption that nothing important moved is exactly the
//! wrong bet. The `db.version` is *not* refused — 1, 2 and 3 differ only in how
//! groups are stored, and both spellings are handled.

